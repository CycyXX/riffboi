export const FONT_CHARS = Object.keys(GLYPHS).join('');

// Draw text straight onto a 2D canvas (used when baking textures).
export function drawGlyphText(ctx, str, x, y, color, scale = 1) {
  ctx.fillStyle = color;
  let cx = x;
  for (const ch of String(str).toUpperCase()) {
    const g = GLYPHS[ch];
    if (g) {
      g.split(' ').forEach((row, ry) => {
        for (let rx = 0; rx < row.length; rx++) {
          if (row[rx] === '#') ctx.fillRect(cx + rx * scale, y + ry * scale, scale, scale);
        }
      });
    }
    cx += 6 * scale;
  }
}
